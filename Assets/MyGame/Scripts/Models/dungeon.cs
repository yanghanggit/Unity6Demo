

using System.Collections.Generic;

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/// <summary>
/// 表示战斗的状态 Phase
/// </summary>
public enum CombatPhase
{
    NONE = 0,
    KICKOFF = 1,  // 初始化，需要同步一些数据与状态
    ONGOING = 2,  // 运行中，不断进行战斗推理
    COMPLETE = 3,  // 结束，需要进行结算
    POSTWAIT = 4  // 战斗等待进入新一轮战斗或者回家
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/// <summary>
/// 表示战斗的状态
/// </summary>
public enum CombatResult
{
    NONE = 0,
    HERO_WIN = 1,  // 胜利
    HERO_LOSE = 2  // 失败
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/// <summary>
/// 状态效果：增益 / 减益，持续伤害 / 持续治疗等
/// </summary>
[System.Serializable]
public sealed class StatusEffect
{
    public string name = "";        // 效果名称
    public string description = ""; // 效果描述
    public int duration = 0;          // 持续回合数
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/// <summary>
/// 代表一张卡牌
/// </summary>
[System.Serializable]
public sealed class Card
{
    public string name = "";        // 卡牌名称
    public string description = ""; // 卡牌效果、作用方式及使用代价
    public List<string> targets = new List<string>();      // 目标对象
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/// <summary>
/// 表示一个回合
/// </summary>
[System.Serializable]
public sealed class Round
{
    public string tag = "";                                // 回合标签，记录回合序号等信息
    public List<string> action_order = new List<string>(); // 行动顺序，按顺序记录角色名称
    public string combat_log = "";                         // 战斗计算日志
    public string narrative = "";                          // 叙事文本/演出描述
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/// <summary>
/// 表示一个战斗
/// </summary>
[System.Serializable]
public sealed class Combat
{
    public string name = "";
    public CombatPhase phase = CombatPhase.NONE;
    public CombatResult result = CombatResult.NONE;
    public List<Round> rounds = new List<Round>();
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/// <summary>
/// 战斗参与
/// </summary>
[System.Serializable]
public sealed class CombatSequence
{
    public List<Combat> combats = new List<Combat>();
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
/// <summary>
/// 地下城
/// </summary>
[System.Serializable]
public sealed class Dungeon
{
    public string name = "";
    public List<Stage> stages = new List<Stage>();
    public CombatSequence combat_sequence = new CombatSequence();
    public int current_stage_index = -1;
}

